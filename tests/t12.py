# 3.2: Stimmungsfeld (Stimmung x Energie, erst Loslassen trägt ein), Gefühle in Gruppen, Kopfschmerzen mit Regler
import subprocess, time
from playwright.sync_api import sync_playwright
srv = subprocess.Popen(['python3','-m','http.server','8765'], cwd='/home/claude/tracker', stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
res=[]
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width':390,'height':780}, service_workers='block')
    ctx.add_init_script("localStorage.setItem('tracker-fb-off','1')")
    pg = ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(700); pg.add_style_tag(content='#fb{pointer-events:none}')
    pg.evaluate("DB.cfg.fold={};render()")
    f=pg.locator('#mfield'); f.scroll_into_view_if_needed(); bb=f.bounding_box()
    X=lambda v: bb['x']+(v-1)/4*bb['width']; Y=lambda e: bb['y']+(5-e)/4*bb['height']
    pg.mouse.move(X(2),Y(2)); pg.mouse.down(); pg.mouse.move(X(3),Y(3),steps=4); pg.mouse.move(X(4.2),Y(4),steps=4)
    res.append(('noch nicht gespeichert', pg.evaluate("!(day(todayStr()).mood||{}).log") and 'gut · 4,2 · wach' in pg.inner_text('#mood-l')))
    pg.mouse.up(); pg.wait_for_timeout(150)
    L=pg.evaluate("day(todayStr()).mood.log")
    res.append(('beim loslassen', len(L)==1 and abs(L[0]['v']-4.2)<=0.1 and abs(L[0]['e']-4)<=0.1, L))
    pg.locator('#mfield').scroll_into_view_if_needed(); bb=pg.locator('#mfield').bounding_box()
    pg.mouse.click(X(1.6),Y(1.5)); pg.wait_for_timeout(150)
    L=pg.evaluate("day(todayStr()).mood.log")
    res.append(('aktiver eintrag geändert', len(L)==1 and abs(L[0]['v']-1.6)<=0.1))
    pg.click('[data-act=mnew]'); bb=pg.locator('#mfield').bounding_box(); pg.mouse.click(X(4.6),Y(4.5)); pg.wait_for_timeout(150)
    res.append(('zweiter eintrag + punkte', pg.evaluate("day(todayStr()).mood.log.length")==2 and pg.locator('#mfield .mpt:not(.live)').count()==2))
    res.append(('gruppen', all(t in pg.inner_text('#app') for t in ['Angenehm','Unangenehm','Körper','überfordert','Kopfschmerzen'])))
    pg.click('#app [data-act=tag][data-v=Kopfschmerzen]'); pg.wait_for_timeout(150)
    r=pg.locator('#app [data-rng="mood.kopf"]')
    res.append(('kopf regler', r.count()==1 and r.input_value()=='3' and pg.evaluate("day(todayStr()).mood.kopf")==3))
    r.evaluate("e=>{e.value=5;e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}))}")
    res.append(('kopf 5', pg.evaluate("day(todayStr()).mood.kopf")==5 and 'sehr stark' in pg.inner_text('#app')))
    pg.locator('#app .card').first.screenshot(path='/tmp/mood.png')
    pg.click('#app [data-act=tag][data-v=Kopfschmerzen]'); pg.wait_for_timeout(150)
    res.append(('kopf weg', pg.evaluate("day(todayStr()).mood.kopf")==None))
    # alter Tag mit altem Gefühl
    pg.evaluate("DB.days[addDays(todayStr(),-1)]={mood:{v:3,tags:['energiegeladen']}};S.date=addDays(todayStr(),-1);render()")
    res.append(('altes gefühl sichtbar', 'energiegeladen' in pg.inner_text('#app')))
    pg.evaluate("S.date=todayStr();A.ciopen()"); pg.click('[data-act=cinext]'); pg.wait_for_timeout(100)
    res.append(('check-in gruppen', 'Körper' in pg.inner_text('#sbody')))
    res.append(('breite', pg.evaluate("document.documentElement.scrollWidth<=390")))
    res.append(('fehler', not errs, errs))
    b.close()
srv.kill()
for x in res: print('OK ' if x[1] else 'FAIL', x[0], *(x[2:] if not x[1] else []))
